"""Packages own modes. No mode exists outside one.

A mode's identity is ``<package>/<name>``, and that is the key everything else
resolves through. The flat, bare-name registry it replaces had two problems that
only show up once more than one person creates modes:

- Two packages cannot own a mode with the same short name. A clash is resolved by
  source precedence, silently, so a contributor whose mode was shadowed cannot
  find out.
- Nothing groups modes, so there is no answer to "what does this package offer".

Discovery stays a flat directory scan because ``WorkflowRegistry`` globs
``*.py`` without recursing, so nesting by directory would make modes invisible.
The package lives in the file name and in the registry ``meta`` instead, which
keeps the existing discovery working while giving every mode an owner.

Lifecycle is explicit: add, remove, enable, disable, import. Disabling keeps a
mode and its history while taking it out of the runnable list, which is what you
want for a mode that is being reworked rather than one that is finished with.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import structlog

log = structlog.get_logger()

WORKFLOWS = Path(".factory") / "workflows"
CATALOGUE = Path(".factory") / "modes.json"

_BARE = re.compile(r"^[a-z0-9][a-z0-9_-]*$")


class ModeIdError(ValueError):
    """A mode identifier is not ``<package>/<name>``."""


def mode_id(package: str, name: str) -> str:
    """The canonical identifier, validated.

    A bare name is refused rather than defaulted into a package: defaulting is
    how a flat namespace grows back, one convenient call at a time.
    """
    for part, label in ((package, "package"), (name, "name")):
        if not _BARE.match(part or ""):
            raise ModeIdError(
                f"{label} {part!r} must be lower-case letters, digits, '-' or '_'"
            )
    return f"{package}/{name}"


def split(identifier: str) -> tuple[str, str]:
    """Split a ``<package>/<name>`` identifier, refusing a bare name."""
    if "/" not in identifier:
        raise ModeIdError(
            f"{identifier!r} is not package-qualified; a mode must live in a "
            "package, e.g. 'refactory/circle_packing_loop'"
        )
    package, name = identifier.split("/", 1)
    return package, name


def _wrapper_file(project: Path, identifier: str) -> Path:
    package, name = split(identifier)
    return Path(project) / WORKFLOWS / f"{package}__{name}.py"


def _catalogue(project: Path) -> dict[str, Any]:
    path = Path(project) / CATALOGUE
    if not path.exists():
        return {"modes": {}}
    try:
        loaded = json.loads(path.read_text())
    except json.JSONDecodeError:
        return {"modes": {}}
    return loaded if isinstance(loaded, dict) else {"modes": {}}


def _save_catalogue(project: Path, data: dict[str, Any]) -> None:
    path = Path(project) / CATALOGUE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, default=str))


def register(project: Path, identifier: str, graph_path: Path, *, description: str = "") -> Path:
    """Register a mode under its package and write the discovery wrapper.

    The wrapper is what ``WorkflowRegistry`` finds: it exposes ``meta`` with the
    package-qualified name and a ``workflow()`` that loads the graph. That is how
    a created mode becomes selectable by name instead of by absolute path.
    """
    _package, name = split(identifier)
    target = _wrapper_file(project, identifier)
    target.parent.mkdir(parents=True, exist_ok=True)
    graph_abs = Path(graph_path).resolve()
    target.write_text(
        '"""Registered mode. Generated by refactory-dsh; edit the graph instead."""\n'
        "import json\n"
        "from pathlib import Path\n"
        "from factory.workflow.primitives import Workflow\n\n"
        f"meta = {{'name': {identifier!r}, 'description': {description!r}}}\n\n"
        "def workflow():\n"
        f"    return Workflow.from_dict(json.loads(Path({str(graph_abs)!r}).read_text()))\n"
    )
    catalogue = _catalogue(project)
    catalogue["modes"][identifier] = {
        "package": _package,
        "name": name,
        "graph": str(graph_abs),
        "wrapper": str(target),
        "description": description,
        "enabled": True,
    }
    _save_catalogue(project, catalogue)
    log.info("mode_registered", mode=identifier, wrapper=str(target))
    return target


def remove(project: Path, identifier: str) -> bool:
    """Remove a mode: its wrapper, its catalogue entry, and its enablement."""
    catalogue = _catalogue(project)
    entry = catalogue["modes"].pop(identifier, None)
    _save_catalogue(project, catalogue)
    wrapper = _wrapper_file(project, identifier)
    if wrapper.exists():
        wrapper.unlink()
    if entry is None and not wrapper.exists():
        return False
    log.info("mode_removed", mode=identifier)
    return True


def set_enabled(project: Path, identifier: str, enabled: bool) -> bool:
    catalogue = _catalogue(project)
    entry = catalogue["modes"].get(identifier)
    if entry is None:
        return False
    entry["enabled"] = enabled
    _save_catalogue(project, catalogue)
    log.info("mode_enabled" if enabled else "mode_disabled", mode=identifier)
    return True


def import_mode(project: Path, source: Path, *, package: str) -> str:
    """Import a mode graph from elsewhere into a package.

    Import copies rather than links, so the imported mode keeps working if the
    original is moved. The caller supplies the package: an import that guessed
    one would make the grouping meaningless.
    """
    source = Path(source)
    payload = json.loads(source.read_text())
    name = str(payload.get("name") or source.stem)
    identifier = mode_id(package, name)
    destination = Path(project) / WORKFLOWS / "graphs" / f"{package}__{name}.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(payload, indent=2))
    register(project, identifier, destination, description=f"imported from {source}")
    return identifier


def catalogue(project: Path) -> dict[str, list[dict[str, Any]]]:
    """Modes grouped by package, which is the only way they are ever listed."""
    grouped: dict[str, list[dict[str, Any]]] = {}
    for identifier, entry in _catalogue(project).get("modes", {}).items():
        try:
            package, _name = split(identifier)
        except ModeIdError:
            continue
        grouped.setdefault(package, []).append({"id": identifier, **entry})
    for modes in grouped.values():
        modes.sort(key=lambda m: m["id"])
    return dict(sorted(grouped.items()))


def resolve(project: Path, identifier: str) -> str | None:
    """The graph path for a package-qualified mode that exists and is enabled."""
    entry = _catalogue(project).get("modes", {}).get(identifier)
    if entry is None or not entry.get("enabled", True):
        return None
    graph = entry.get("graph")
    return graph if graph and Path(graph).exists() else None


def enabled_ids(project: Path) -> list[str]:
    return sorted(
        i for i, e in _catalogue(project).get("modes", {}).items() if e.get("enabled", True)
    )


def render_catalogue(project: Path) -> str:
    """The grouped listing a user sees."""
    grouped = catalogue(project)
    if not grouped:
        return "no modes registered\n"
    lines = []
    for package, modes in grouped.items():
        lines.append(f"{package}/")
        for mode in modes:
            state = "" if mode.get("enabled", True) else "  (disabled)"
            lines.append(f"  {mode['name']:<28} {mode.get('description', '')}{state}")
    return "\n".join(lines) + "\n"
