"""Deterministic scaffold ops for the create_v2 / design_v2 meta-modes.

These replace refactory's ``factory discover/init/study/graph update/precheck``
CLI calls with plain filesystem ops. They run as subprocesses (cwd = the run
workdir), read the node manifest from ``DSH_WORKFLOW_NODE``, and create the
``.factory`` files the graph's data-dependency check expects.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

FACTORY = Path(".factory")


def _node() -> dict:
    return json.loads(os.environ.get("DSH_WORKFLOW_NODE", "{}"))


def _intent() -> str:
    return os.environ.get("REFACTORY_INTENT", "Build something useful.")


def _writes(node: dict) -> list[str]:
    return node.get("writes") or []


def discover() -> None:
    """Create the discovery summary the graph reads next."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "discovery.json").write_text(json.dumps({
        "project": os.environ.get("REFACTORY_WORKDIR", os.getcwd()),
        "has_factory": (FACTORY / "config.json").exists(),
    }, indent=2))


def init() -> None:
    """Write a minimal factory config."""
    FACTORY.mkdir(exist_ok=True)
    if not (FACTORY / "config.json").exists():
        (FACTORY / "config.json").write_text(json.dumps({
            "name": "refactory-dsh",
            "version": "0.1.0",
            "intent": _intent(),
        }, indent=2))


def study() -> None:
    """Write empty study observations so the graph can advance."""
    strategy = FACTORY / "strategy"
    strategy.mkdir(parents=True, exist_ok=True)
    for name in ("observations.md", "graph-context.md"):
        p = strategy / name
        if not p.exists():
            p.write_text(f"# {name.removesuffix('.md')}\n\n(generated by refactory-dsh study)\n")


def graph_update() -> None:
    """Emit the created mode's graph.json (a basic circle-packing inner loop)."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "graph.updated").write_text("ok\n")
    _emit_basic_loop()


def _emit_basic_loop() -> None:
    """Write the circle-packing inner loop as the created mode's IR.

    create-v2 produces this loop — seed the loop state, select a parent, generate
    a candidate, consult the budget gate, then evaluate the candidate and accept or
    reject it — with one `OptKnob`, `acceptance_mode`, so the outer loop has a real
    declared knob to mutate. The deterministic nodes reuse SRF's ops (which the
    science runner already drives); the LLM node writes `candidate.py`.

    The gate sits immediately downstream of `generate`, the only node the driver is
    ever handed, so a repeated completion report of that node re-advances the walk
    onto the gate — a pure read of `budget_state.json` (`budget.py:62-76`) — rather
    than onto `eval`, which would evaluate the same candidate a second time.
    """
    generate_brief = (
        "Write candidate.py: a complete Python module defining solve(n: int, radii: list[float]) "
        "-> list[tuple[float, float]] that returns exactly n (x, y) centres inside the unit square. "
        "Start from the parent program in selected_parent.json and change it to score higher than that "
        "parent's recorded score. The module must import cleanly and must not import os or subprocess, "
        "open files, or run shell commands."
    )
    # `seed_run` writes the six loop-state files and `accept` rewrites them; one
    # list keeps the two declarations from drifting apart.
    loop_state = [
        "accepted_history.json", "best_solution.py", "genealogy.json",
        "gepa_state.json", "population.json", "rejection_history.json",
    ]
    # `accept` also appends the two JSONL traces unconditionally on entry
    # (`acceptance.py:44-45`). `run_eval` is the only consumer of a declared write
    # list (`sandbox.py:50-55`) and it selects the alphabetically-first `.json`; a
    # `.jsonl` name never matches that suffix, and `accept` runs no `run_eval`.
    accept_writes = loop_state + ["candidates.jsonl", "evaluations.jsonl"]
    modes = FACTORY / "modes"
    modes.mkdir(parents=True, exist_ok=True)
    graph = {
        "name": "circle_packing_loop",
        "nodes": {
            "task_input": {
                "id": "task_input", "reads": [], "blocking": True,
                "writes": ["task.yaml", "eval.py", "initial.py", "knobs.json", "budget_state.json"],
                "command": "python -m srf.ops.common.task_input", "_type": "FnNode",
            },
            "seed_run": {
                "id": "seed_run", "reads": [], "blocking": True,
                "writes": loop_state,
                "command": "python -m srf.ops.common.seed accepted_history.json best_solution.py "
                           "genealogy.json gepa_state.json population.json rejection_history.json",
                "_type": "FnNode",
            },
            "select_parent": {
                "id": "select_parent", "reads": ["gepa_state.json", "population.json"], "blocking": True,
                # `select_parent` also saves the state it just loaded (`population.py:28-30` →
                # `state.py:33-34`). `run_eval` is the only consumer of a declared write list
                # (`sandbox.py:50-55`) and this node does not run it.
                "writes": ["gepa_state.json", "selected_parent.json"],
                "command": "python -m srf.ops.run srf.ops.gepa.population:select_parent",
                "_type": "FnNode",
            },
            "generate": {
                "id": "generate",
                "reads": ["task.yaml", "initial.py", "selected_parent.json", "rejection_history.json"],
                "writes": ["candidate.py"], "blocking": True, "system_prompt": generate_brief,
                "instance_prompt": "", "temperature": 0.7,
                "_type": "LLMNode",
            },
            "eval": {
                # `run_eval` picks its result file as the alphabetically-first `.json` write
                # (`sandbox.py:50-55`), so `budget_state.json` — which this node also rewrites
                # through `record_eval` (`sandbox.py:88-89` → `budget.py:37-40`) — must NOT be
                # declared: it sorts before `eval_result.json`, the score clobbers the counter
                # and `record_eval` raises `KeyError: 'eval_count'`. `budget.jsonl` does not end
                # in `.json`, so declaring it is selection-safe. The same op reads the counter
                # (`budget.py:38`), so `budget_state.json` is declared as a read instead;
                # `task_input` is its only writer and always precedes this node.
                "id": "eval", "reads": ["budget_state.json", "candidate.py", "task.yaml"],
                "writes": ["budget.jsonl", "eval_result.json"],
                "blocking": True,
                "command": "python -m srf.ops.run srf.ops.common.sandbox:run_eval", "_type": "FnNode",
            },
            "accept": {
                "id": "accept", "blocking": True,
                "reads": ["candidate.py", "eval_result.json", "genealogy.json", "gepa_state.json",
                          "population.json", "selected_parent.json"],
                "writes": accept_writes,
                "command": "python -m srf.ops.run srf.ops.gepa.acceptance:accept_or_reject",
                "_type": "FnNode",
            },
            "budget_check": {
                "id": "budget_check", "reads": ["budget_state.json"], "writes": [], "blocking": True,
                "evaluator_type": "fn",
                "evaluator_command": "python -m srf.ops.common.budget check",
                "max_iterations": 500,
                "_type": "GateNode",
            },
            "exit": {
                "id": "exit", "reads": [], "writes": [], "blocking": True,
                "command": "true", "_type": "FnNode",
            },
        },
        # Every non-gate node has exactly one outgoing edge and it is unconditional:
        # `advance()` replaces a completed node with its `unconditionalTarget`, so a
        # non-gate node whose only out-edges are conditional ends the walk `done`.
        # The reloop lands on `eval`, and `uncompleteBetween(eval, budget_check)`
        # (`spine.ts:234-257`) un-completes `eval`, `accept`, `select_parent` and
        # `generate`, so `select_parent` re-runs on every iteration and the incumbent
        # in `selected_parent.json` stays live for the next `accept`.
        "edges": [
            {"source": "task_input", "target": "seed_run", "condition": None},
            {"source": "seed_run", "target": "select_parent", "condition": None},
            {"source": "select_parent", "target": "generate", "condition": None},
            {"source": "generate", "target": "budget_check", "condition": None},
            {"source": "eval", "target": "accept", "condition": None},
            {"source": "accept", "target": "select_parent", "condition": None},
            {"source": "budget_check", "target": "eval", "condition": "reloop"},
            {"source": "budget_check", "target": "exit", "condition": "proceed"},
        ],
        "start_node": "task_input",
        "terminal": True,
        "knob_values": {"acceptance_mode": "strict"},
        "knob_bounds": {"acceptance_mode": ["strict", "lenient", "off"]},
        "knob_specs": {
            "acceptance_mode": {
                "kind": "prompt", "node_id": "accept", "default": "strict",
                "bounds": ["strict", "lenient", "off"], "expandable": False,
                "expansion_hint": "",
                "description": "acceptance strictness: consumed by srf.ops.gepa.acceptance via SRF_KNOBS; "
                               "live only when the value is delivered with --knobs (the outer loop does; "
                               "a direct science run passes {})",
            },
        },
    }
    emitted = modes / "circle_packing_loop.graph.json"
    emitted.write_text(json.dumps(graph, indent=2))
    # Pin the optimizable surface here, at the only moment its author can still
    # cheaply fix a knob that nothing reads (see refactory_dsh.knobs).
    from refactory_dsh.knobs import pin

    surface = pin(emitted)
    # A created mode has to land somewhere with an owner, or the outer loop can
    # only reach it by absolute path (see refactory_dsh.packages).
    from refactory_dsh import packages

    package = os.environ.get("REFACTORY_PACKAGE", "refactory").strip() or "refactory"
    identifier = packages.register(
        Path.cwd(), packages.mode_id(package, graph["name"]), emitted,
        description="generated by create-v2",
    )
    print(json.dumps({
        "registered_as": f"{package}/{graph['name']}",
        "emitted": str(emitted),
        "optimizable_knobs": [k["name"] for k in surface["knobs"]],
        "dead_knobs": [d["name"] for d in surface["dead"]],
        "unverified_knobs": [u["name"] for u in surface["unverified"]],
    }))


def precheck() -> None:
    """Report the project is ready (a gate prints the decision)."""
    print("PROCEED")


def check_factory_exists() -> None:
    print("PROCEED" if (FACTORY / "config.json").exists() else "HALT")


def check_factory_md() -> None:
    print("PROCEED" if Path("factory.md").exists() else "HALT")


def concat_study() -> None:
    """Concatenate the study observations into one combined file."""
    strategy = FACTORY / "strategy"
    a = strategy / "observations.md"
    b = strategy / "graph-context.md"
    out = strategy / "study-combined.md"
    out.write_text(a.read_text() + "\n" + b.read_text())


def intent_init() -> None:
    """Write the user intent file the research nodes read."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "user-intent.md").write_text(f"# Intent\n\n{_intent()}\n")


def qa_synthesis() -> None:
    """Write an empty QA synthesis (the QA gate reads it)."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "qa-synthesis.md").write_text("# QA synthesis\n\n(generated by refactory-dsh)\n")


def spec_generate() -> None:
    """Write an empty spec (design_v2's spec-generate step)."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "spec.md").write_text(f"# Spec\n\n{_intent()}\n")



# ── mode lifecycle ─────────────────────────────────────────────────────────
# Packages own modes; there is no bare-name mode. These verbs are the whole
# lifecycle, so a mode is added, listed, disabled and removed through one
# interface rather than by editing files.


def mode_list() -> None:
    """List modes grouped by package."""
    from refactory_dsh import packages

    print(packages.render_catalogue(Path.cwd()))


def mode_add() -> None:
    """Register a mode: `mode_add <package> <name> <graph.json>`."""
    from refactory_dsh import packages

    if len(sys.argv) < 5:
        print("usage: mode_add <package> <name> <graph.json>", file=sys.stderr)
        sys.exit(2)
    package, name, graph = sys.argv[2], sys.argv[3], sys.argv[4]
    packages.register(Path.cwd(), packages.mode_id(package, name), Path(graph))
    print(json.dumps({"added": f"{package}/{name}"}))


def mode_import() -> None:
    """Import a mode graph into a package: `mode_import <package> <graph.json>`."""
    from refactory_dsh import packages

    if len(sys.argv) < 4:
        print("usage: mode_import <package> <graph.json>", file=sys.stderr)
        sys.exit(2)
    identifier = packages.import_mode(Path.cwd(), Path(sys.argv[3]), package=sys.argv[2])
    print(json.dumps({"imported": identifier}))


def mode_remove() -> None:
    """Remove a mode: `mode_remove <package>/<name>`."""
    from refactory_dsh import packages

    if len(sys.argv) < 3:
        print("usage: mode_remove <package>/<name>", file=sys.stderr)
        sys.exit(2)
    ok = packages.remove(Path.cwd(), sys.argv[2])
    print(json.dumps({"removed": sys.argv[2], "found": ok}))


def mode_enable() -> None:
    """Enable a mode: `mode_enable <package>/<name>`."""
    from refactory_dsh import packages

    print(json.dumps({"enabled": sys.argv[2],
                      "found": packages.set_enabled(Path.cwd(), sys.argv[2], True)}))


def mode_disable() -> None:
    """Disable a mode without removing it: `mode_disable <package>/<name>`."""
    from refactory_dsh import packages

    print(json.dumps({"disabled": sys.argv[2],
                      "found": packages.set_enabled(Path.cwd(), sys.argv[2], False)}))


_COMMANDS = {
    "discover": discover,
    "init": init,
    "study": study,
    "graph_update": graph_update,
    "mode_emit": _emit_basic_loop,
    "precheck": precheck,
    "check_factory_exists": check_factory_exists,
    "check_factory_md": check_factory_md,
    "concat_study": concat_study,
    "intent_init": intent_init,
    "qa_synthesis": qa_synthesis,
    "spec_generate": spec_generate,
    "mode_list": mode_list, "mode_add": mode_add, "mode_import": mode_import,
    "mode_remove": mode_remove, "mode_enable": mode_enable, "mode_disable": mode_disable,
}


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in _COMMANDS:
        print(f"usage: python -m refactory_dsh.ops.scaffold <{'|'.join(_COMMANDS)}>", file=sys.stderr)
        sys.exit(2)
    _COMMANDS[sys.argv[1]]()


if __name__ == "__main__":
    main()
