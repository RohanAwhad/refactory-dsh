"""Deterministic scaffold ops for the create_v2 / design_v2 meta-modes.

These replace refactory's ``factory discover/init/study/graph update/precheck``
CLI calls with plain filesystem ops. They run as subprocesses (cwd = the run
workdir), read the node manifest from ``DSH_WORKFLOW_NODE``, and create the
``.factory`` files the graph's data-dependency check expects.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

FACTORY = Path(".factory")


def _node() -> dict:
    return json.loads(os.environ.get("DSH_WORKFLOW_NODE", "{}"))


def _intent() -> str:
    return os.environ.get("REFACTORY_INTENT", "Build something useful.")


def _writes(node: dict) -> list[str]:
    return node.get("writes") or []


def discover() -> None:
    """Create the discovery summary the graph reads next."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "discovery.json").write_text(json.dumps({
        "project": os.environ.get("REFACTORY_WORKDIR", os.getcwd()),
        "has_factory": (FACTORY / "config.json").exists(),
    }, indent=2))


def init() -> None:
    """Write a minimal factory config."""
    FACTORY.mkdir(exist_ok=True)
    if not (FACTORY / "config.json").exists():
        (FACTORY / "config.json").write_text(json.dumps({
            "name": "refactory-dsh",
            "version": "0.1.0",
            "intent": _intent(),
        }, indent=2))


def study() -> None:
    """Write empty study observations so the graph can advance."""
    strategy = FACTORY / "strategy"
    strategy.mkdir(parents=True, exist_ok=True)
    for name in ("observations.md", "graph-context.md"):
        p = strategy / name
        if not p.exists():
            p.write_text(f"# {name.removesuffix('.md')}\n\n(generated by refactory-dsh study)\n")


def graph_update() -> None:
    """Emit the created mode's graph.json (a basic circle-packing inner loop)."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "graph.updated").write_text("ok\n")
    _emit_basic_loop()


def _emit_basic_loop() -> None:
    """Write a minimal circle-packing inner loop as the created mode's IR.

    create-v2 produces this *basic* loop (generate → eval → accept, budget-gated)
    with two `OptKnob`s — `temperature` and `acceptance_mode` — so the outer loop
    has real declared knobs to mutate. The deterministic nodes reuse SRF's ops
    (which the science runner already drives); the LLM node writes `candidate.py`.
    """
    modes = FACTORY / "modes"
    modes.mkdir(parents=True, exist_ok=True)
    graph = {
        "name": "circle_packing_loop",
        "nodes": {
            "task_input": {
                "id": "task_input", "reads": [], "blocking": True,
                "writes": ["task.yaml", "eval.py", "initial.py", "knobs.json", "budget_state.json"],
                "command": "python -m srf.ops.common.task_input", "_type": "FnNode",
            },
            "generate": {
                "id": "generate", "reads": ["task.yaml", "initial.py"],
                "writes": ["candidate.py"], "blocking": True, "system_prompt": "",
                "instance_prompt": "Write candidate.py to solve the task.", "temperature": 0.7,
                "_type": "LLMNode",
            },
            "eval": {
                "id": "eval", "reads": ["candidate.py"], "writes": ["score.json", "budget_state.json"],
                "blocking": True,
                "command": "python -m srf.ops.run srf.ops.common.sandbox:run_eval", "_type": "FnNode",
            },
            "accept": {
                "id": "accept", "reads": ["score.json"], "writes": [], "blocking": True,
                "evaluator_type": "fn",
                "evaluator_command": "python -m srf.ops.run srf.ops.gepa.acceptance:accept_or_reject",
                "_type": "GateNode",
            },
            "budget_check": {
                "id": "budget_check", "reads": ["budget_state.json"], "writes": [], "blocking": True,
                "evaluator_type": "fn",
                "evaluator_command": "python -m srf.ops.common.budget check",
                "_type": "GateNode",
            },
            "exit": {
                "id": "exit", "reads": [], "writes": [], "blocking": True,
                "command": "true", "_type": "FnNode",
            },
        },
        "edges": [
            {"source": "task_input", "target": "generate", "condition": None},
            {"source": "generate", "target": "eval", "condition": None},
            {"source": "eval", "target": "accept", "condition": None},
            {"source": "accept", "target": "budget_check", "condition": "proceed"},
            {"source": "accept", "target": "generate", "condition": "reloop"},
            {"source": "budget_check", "target": "generate", "condition": "reloop"},
            {"source": "budget_check", "target": "exit", "condition": "proceed"},
        ],
        "start_node": "task_input",
        "terminal": True,
        "knob_values": {"temperature": 0.7, "acceptance_mode": "strict"},
        "knob_bounds": {"temperature": [0.3, 0.5, 0.7, 0.9, 1.0], "acceptance_mode": ["strict", "lenient"]},
        "knob_specs": {
            "temperature": {
                "kind": "threshold", "node_id": "generate", "default": 0.7,
                "bounds": [0.3, 0.5, 0.7, 0.9, 1.0], "expandable": False,
                "expansion_hint": "", "description": "LLM sampling temperature",
            },
            "acceptance_mode": {
                "kind": "prompt", "node_id": "accept", "default": "strict",
                "bounds": ["strict", "lenient"], "expandable": False,
                "expansion_hint": "", "description": "acceptance strictness",
            },
        },
    }
    (modes / "circle_packing_loop.graph.json").write_text(json.dumps(graph, indent=2))
    print(f"emitted {modes / 'circle_packing_loop.graph.json'}")


def precheck() -> None:
    """Report the project is ready (a gate prints the decision)."""
    print("PROCEED")


def check_factory_exists() -> None:
    print("PROCEED" if (FACTORY / "config.json").exists() else "HALT")


def check_factory_md() -> None:
    print("PROCEED" if Path("factory.md").exists() else "HALT")


def concat_study() -> None:
    """Concatenate the study observations into one combined file."""
    strategy = FACTORY / "strategy"
    a = strategy / "observations.md"
    b = strategy / "graph-context.md"
    out = strategy / "study-combined.md"
    out.write_text(a.read_text() + "\n" + b.read_text())


def intent_init() -> None:
    """Write the user intent file the research nodes read."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "user-intent.md").write_text(f"# Intent\n\n{_intent()}\n")


def qa_synthesis() -> None:
    """Write an empty QA synthesis (the QA gate reads it)."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "qa-synthesis.md").write_text("# QA synthesis\n\n(generated by refactory-dsh)\n")


def spec_generate() -> None:
    """Write an empty spec (design_v2's spec-generate step)."""
    FACTORY.mkdir(exist_ok=True)
    (FACTORY / "spec.md").write_text(f"# Spec\n\n{_intent()}\n")


_COMMANDS = {
    "discover": discover,
    "init": init,
    "study": study,
    "graph_update": graph_update,
    "mode_emit": _emit_basic_loop,
    "precheck": precheck,
    "check_factory_exists": check_factory_exists,
    "check_factory_md": check_factory_md,
    "concat_study": concat_study,
    "intent_init": intent_init,
    "qa_synthesis": qa_synthesis,
    "spec_generate": spec_generate,
}


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in _COMMANDS:
        print(f"usage: python -m refactory_dsh.ops.scaffold <{'|'.join(_COMMANDS)}>", file=sys.stderr)
        sys.exit(2)
    _COMMANDS[sys.argv[1]]()


if __name__ == "__main__":
    main()
