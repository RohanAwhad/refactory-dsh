"""Native equivalents for Create's existing-mode and plugin variants.

Revisions are isolated candidates under the original qualified identity. The
source workspace is never edited. A plugin is a distributable native Package,
installed by the native registry copy/import lifecycle, not a remote entry point.
"""
from __future__ import annotations

import base64
import hashlib
import json
import shutil
import tempfile
from pathlib import Path
from typing import Any

from refactory_dsh import registry, sandbox

BASELINE = ".factory/create-baseline.json"


def source_import_code(name: str) -> str:
    """Contained candidate imports must execute current source, not stale pyc.

    Python timestamp caches may validate a same-size rewrite within one second.
    Only this candidate's namespace bypasses caches; framework/dependency
    loading and source bytes are untouched. The override dies with the child.
    """
    return "\n".join([
        "from importlib.machinery import SourceFileLoader",
        "_native_original_get_code=SourceFileLoader.get_code",
        f"_native_package_prefix={'refactory_packages.' + name!r}",
        "def _native_current_source(self, fullname):",
        "    if fullname == _native_package_prefix or fullname.startswith(_native_package_prefix+'.'):",
        "        return self.source_to_code(self.get_data(self.path), self.path)",
        "    return _native_original_get_code(self, fullname)",
        "SourceFileLoader.get_code=_native_current_source",
    ])


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def inventory(root: Path) -> dict[str, dict[str, Any]]:
    """All package files except Python's generated bytecode cache.

    Origin/admission receipts, SKILL.md, tests and arbitrary cache-named content
    are retained. An authored digest alone cannot establish whole-package reuse.
    """
    result = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"revision package contains a symlink: {path}")
        if not path.is_file() or "__pycache__" in path.relative_to(root).parts or path.suffix == ".pyc":
            continue
        data = path.read_bytes()
        result[path.relative_to(root).as_posix()] = {"sha256": sha(data), "bytes": len(data),
                                                  "base64": base64.b64encode(data).decode(),
                                                  "text": data.decode("utf-8", errors="replace")}
    return result


def snapshot_revision(source: Path, run: Path, name: str, identifier: str) -> dict[str, Any]:
    """Copy the existing workspace package without importing source code."""
    package, _ = registry.split(identifier)
    if package != name:
        raise ValueError("update-existing name must equal revision_of's package; identity is preserved")
    if source.resolve() == run.resolve():
        raise ValueError("update-existing requires a separate authoring run to preserve the original project")
    root = registry.workspace_root(source) / name
    if root.is_symlink() or not root.resolve().is_relative_to(source.resolve()):
        raise ValueError("existing package escapes its source workspace")
    if not (root / "__init__.py").is_file():
        raise ValueError(f"update-existing needs a native workspace package at {root}; installed packages are read-only")
    target = registry.workspace_root(run) / name
    if target.exists():
        raise ValueError("revision candidate already exists without its bound baseline; use a fresh run")
    files = inventory(root)
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(root, target, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    if inventory(root) != files or inventory(target) != files:
        shutil.rmtree(target)
        raise ValueError("source package changed while preparing revision")
    # Import only the isolated copy, through normal native containment.
    from refactory_dsh.create_fidelity_ops import validate_native_package

    report = validate_native_package(run, name)
    modes = {m["id"]: m for m in report.get("modes", [])}
    if not report.get("ok") or identifier not in modes:
        shutil.rmtree(target)
        raise ValueError("revision baseline is invalid or target mode missing: " + "; ".join(report.get("problems", [])))
    if inventory(root) != files:
        shutil.rmtree(target)
        raise ValueError("original package changed during contained baseline inspection")
    return {"schema_version": 1, "variant": "update-existing", "revision_of": identifier,
            "source_project": str(source), "source_package": str(root), "candidate_package": str(target),
            "files": files, "modes": modes, "raw_validation": report["raw_evidence"],
            "publication": "isolated-revision-candidate; original source unchanged"}


def update_check(project: Path, name: str) -> dict[str, Any]:
    from refactory_dsh.create_fidelity_ops import validate_native_package

    project = Path(project).resolve()
    request = json.loads((project / ".factory/create-request.json").read_text())
    data = (project / BASELINE).read_bytes()
    baseline = json.loads(data)
    problems = []
    if (not isinstance(request, dict) or not isinstance(baseline, dict)
            or request.get("name") != name or request.get("variant") != "update-existing"
            or request.get("baseline_sha256") != sha(data)
            or request.get("revision_of") != baseline.get("revision_of")):
        return {"schema_version": 1, "variant": "update-existing", "ok": False,
                "problems": ["revision baseline does not match the original Create request"],
                "source_unchanged": False, "raw_evidence": {}}
    if (baseline.get("schema_version") != 1 or not isinstance(baseline.get("files"), dict)
            or not baseline["files"] or not isinstance(baseline.get("modes"), dict)
            or not baseline["modes"] or not isinstance(baseline.get("source_package"), str)):
        raise ValueError("revision baseline has incomplete source evidence")
    if inventory(Path(baseline["source_package"])) != baseline["files"]:
        problems.append("original source package changed; revision evidence is stale")
    report = validate_native_package(project, name)
    problems.extend(report["problems"])
    modes = {m["id"]: m for m in report.get("modes", [])}
    subject = baseline["revision_of"]
    if subject not in modes:
        problems.append("revised qualified mode identity disappeared")
    for identifier, original in baseline["modes"].items():
        if identifier != subject and modes.get(identifier) != original:
            problems.append(f"unrelated mode declaration changed or disappeared: {identifier}")
    return {"schema_version": 1, "variant": "update-existing", "ok": not problems,
            "problems": problems, "revision_of": subject, "baseline_sha256": sha(data),
            "candidate_package_digest": report.get("package_digest"), "raw_evidence": report.get("raw_evidence"),
            "behavioral_regressions": "not established by structural comparison; run original and revised contract tests",
            "source_unchanged": "original source package changed; revision evidence is stale" not in problems}


def plugin_check(project: Path, name: str) -> dict[str, Any]:
    """Verify installation/discovery/validation/removal in an isolated consumer.

    This is structural lifecycle evidence. It never pretends that importing or
    building a graph executes the user's behavior or a mode requiring a model.
    """
    project = Path(project).resolve()
    registry.split(name + "/probe")  # validate the package component before constructing paths
    root = registry.workspace_root(project) / name
    if root.is_symlink() or not root.resolve().is_relative_to(project):
        raise ValueError("standalone plugin escapes its artifact project")
    before = inventory(root)
    with tempfile.TemporaryDirectory(prefix="plugin-consumer-", dir=project) as temporary:
        consumer = Path(temporary)
        code = "\n".join([
            source_import_code(name),
            "import json", "from pathlib import Path", "from refactory_dsh import registry",
            "from refactory_dsh.nn import validate_state",
            f"consumer=Path({str(consumer)!r})", f"source=Path({str(root)!r})", f"name={name!r}",
            "checks=[]; problems=[]; modes=[]; installed=False",
            "try:",
            "    registry.add(consumer, source); installed=True",
            "    checks.append('native registry.add copied standalone package')",
            "    catalogue=registry.catalogue(consumer)",
            "    if name not in catalogue: problems.append('plugin absent from actual registry catalogue')",
            "    package=registry.load(name, consumer)",
            "    for mode_class in package.modes:",
            "        identifier=name+'/'+mode_class.name",
            "        _, resolved=registry.resolve(consumer, identifier)",
            "        mode=resolved(); issues=validate_state(mode.state_dict(), invariants=mode.invariants(), resolve_calls=True)",
            "        problems.extend(str(issue) for issue in issues); modes.append(identifier)",
            "    if not modes: problems.append('plugin supplies no native modes')",
            "    checks.append('actual catalogue, resolve and native validate_state')",
            "finally:",
            "    if installed:",
            "        registry.remove(consumer, name)",
            "        if registry.where(name, consumer) is not None: problems.append('plugin remains after native removal')",
            "        checks.append('native registry.remove cleaned consumer package')",
            "print(json.dumps({'problems':problems,'modes':modes,'checks':checks,'removed':not (registry.workspace_root(consumer)/name).exists()}))",
        ])
        result = sandbox.run_sandboxed(code, workdir=project)
        removal_probe = sandbox.run_sandboxed("\n".join([
            "import json", "from pathlib import Path", "from refactory_dsh import registry",
            f"consumer=Path({str(consumer)!r})", f"identifier={name + '/'+str((result.payload.get('modes') or ['probe'])[0]).split('/')[-1]!r}",
            "resolved=False",
            "try: registry.resolve(consumer,identifier); resolved=True",
            "except ValueError: pass",
            "print(json.dumps({'resolved_after_remove':resolved}))",
        ]), workdir=project)
    problems = list(result.payload.get("problems", []))
    if not result.ok or not result.payload.get("removed") or not result.payload.get("modes"):
        problems.append(result.problem() or "plugin lifecycle supplied incomplete evidence")
    if not removal_probe.ok or removal_probe.payload.get("resolved_after_remove") is not False:
        problems.append("removed plugin still resolves in a fresh native consumer process")
    if inventory(root) != before:
        problems.append("standalone plugin bytes changed during consumer installation")
    return {"schema_version": 1, "variant": "plugin", "ok": not problems, "problems": problems,
            **{k: result.payload.get(k) for k in ("checks", "modes", "removed")},
            "behavioral_execution": "not exercised by plugin-check; use native run and user contract tests",
            "source_package_sha256": sha(json.dumps(before, sort_keys=True).encode()),
            "remote_entry_points": "not a native mechanism; registry add/import is the explicit equivalent",
            "process_scope": "CLI consumer lifetime; existing module objects in other running Python processes are not revoked",
            "raw_evidence": {"stdout": result.stdout, "stderr": result.stderr, "returncode": result.returncode,
                             "timed_out": result.timed_out, "timeout_s": result.timeout_s,
                             "post_remove_probe": {"stdout": removal_probe.stdout, "stderr": removal_probe.stderr,
                                                   "returncode": removal_probe.returncode, "payload": removal_probe.payload}}}
